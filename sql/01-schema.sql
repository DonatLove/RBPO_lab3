-- Run as database owner/administrator in database lost_and_found.
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(150) NOT NULL CHECK (length(trim(full_name)) > 0),
    contact_details VARCHAR(200) NOT NULL CHECK (length(trim(contact_details)) > 0),
    version BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS found_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description VARCHAR(500) NOT NULL CHECK (length(trim(description)) > 0),
    category VARCHAR(100) NOT NULL CHECK (length(trim(category)) > 0),
    location VARCHAR(200) NOT NULL CHECK (length(trim(location)) > 0),
    status VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE'
        CHECK (status IN ('AVAILABLE', 'RESERVED', 'HANDED_OVER')),
    version BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS loss_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    applicant_id BIGINT NOT NULL,
    description VARCHAR(500) NOT NULL CHECK (length(trim(description)) > 0),
    category VARCHAR(100) NOT NULL CHECK (length(trim(category)) > 0),
    status VARCHAR(30) NOT NULL DEFAULT 'OPEN'
        CHECK (status IN ('OPEN', 'MATCHED', 'CLOSED', 'CLOSED_UNMATCHED')),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_loss_reports_applicant FOREIGN KEY (applicant_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS item_claims (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loss_report_id BIGINT NOT NULL,
    found_item_id BIGINT NOT NULL,
    evidence VARCHAR(1000) NOT NULL CHECK (length(trim(evidence)) > 0),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED', 'HANDED_OVER')),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_item_claims_loss_report FOREIGN KEY (loss_report_id) REFERENCES loss_reports(id),
    CONSTRAINT fk_item_claims_found_item FOREIGN KEY (found_item_id) REFERENCES found_items(id),
    CONSTRAINT uk_item_claims_report_item UNIQUE (loss_report_id, found_item_id)
);

CREATE TABLE IF NOT EXISTS handover_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_claim_id BIGINT NOT NULL,
    handover_time TIMESTAMP NOT NULL,
    confirmed BOOLEAN NOT NULL DEFAULT FALSE,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_handover_records_claim FOREIGN KEY (item_claim_id) REFERENCES item_claims(id),
    CONSTRAINT uk_handover_records_claim UNIQUE (item_claim_id)
);
